      the EU/EEA, using safeguards such as standard contractual clauses where required.
    </p>

    <h2 class="mt-8">Cookies and similar storage</h2>
    <p>
      We use cookies and local storage to keep you logged in, remember your language and login step,
      and keep the site working. Analytics may set its own cookies. You can block or delete cookies
      in your browser; some features, such as staying logged in, then stop working.
    </p>

    <h2 class="mt-8">How long we keep it</h2>
    <p>
      We keep your account data while your account exists. Billing records may be kept longer where
      the law requires. When you ask us to delete your account, we delete your personal data, except
      what we must keep by law.
    </p>
    <p>
      Technical and usage data (such as IP address, browser information and pages visited) is kept
      only as long as needed for security, abuse prevention and usage statistics. How long exactly
      depends on the retention settings of the providers that process it, such as our hosting and
      analytics providers, and it is not kept longer than those purposes require. In Google
      Analytics, user-level and event-level data is kept for 2 months, after which it is deleted
      automatically. Aggregated reports may be kept longer.
    </p>

    <h2 class="mt-8">Your rights</h2>
    <p>
      Under the GDPR you can ask us to access, correct, delete or export your data, to restrict or
      object to some processing, and to withdraw consent where we rely on it. Email
      <a href="mailto:privacy@norskeord.no" class="underline">privacy@norskeord.no</a> and we will reply
      within one month. You can also complain to your national data protection authority; in Norway this
      is Datatilsynet.
    </p>

    <h2 class="mt-8">Children</h2>
    <p>
      Norskeord is not directed at children under 13, and we do not knowingly collect their data. If
      you think a child has given us data, contact us and we will delete it.
    </p>

