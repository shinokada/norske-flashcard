    <h2 class="mt-8">What we collect</h2>
    <ul class="list-disc space-y-1 pl-6">
      <li>
        <strong>Account data.</strong> Your email address when you log in with an email code. If you choose
        "Continue with Google", we receive your Google account email address, and may receive your name
        and profile picture. We never receive your Google password.
      </li>
      <li>
        <strong>Learning data.</strong> Your language preference and your study progress and review schedule,
        so that your progress can sync across devices.
      </li>
      <li>
        <strong>Subscription data.</strong> If you buy Norskeord Plus, your plan and its status and end
        date. Payments are handled by our payment provider; we do not receive or store your card number.
      </li>
      <li>
        <strong>Emails and reminders.</strong> We send login codes, and may send study reminders and welcome
        emails. Emails include an unsubscribe option where it applies.
      </li>
      <li>
        <strong>Technical and usage data.</strong> Basic information such as your IP address, browser
        and pages visited, used for security, abuse prevention and understanding how the site is used.
        For Plus accounts, we also keep daily counts of how many study entries your account requests,
        linked to your account, to detect automated copying of the course.
      </li>
      <li>
        <strong>Country.</strong> When you use the site signed in, we work out your country from your
        connection and store only the two-letter country code on your profile, not your IP address. We
        keep the first one we see and do not update it.
      </li>
    </ul>

